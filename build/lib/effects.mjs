/**
 * Every condition and effect pf2e ships, counted and cut into twelve parts, one issue and one tracker each.
 *
 * `npm run index:pf2e` reads the packs and writes the inventory (`build/data/pf2e-effects.json`) and its
 * readable form (`Docs/pf2e-effects.md`); the words of the items an effect tracker lists go to
 * `build/data/pf2e-effect-text.json`, for its clauses to be held to offline.
 *
 * An item is keyed `<pack>/<slug>` — its id where it has no slug — and the parts follow the packs, so a part
 * is a kind of thing: the conditions and the small packs first, then spell, feat, equipment and creature
 * effects, each pack cut by name into parts of about 250.
 */

/** The packs, in part order, and how many parts each is cut into. A pack sharing a part sits in one group. */
export const PARTS = [
    { packs: ["conditionitems", "other-effects", "campaign-effects", "boons-and-curses"], parts: 1, title: "Conditions, and the small packs" },
    { packs: ["spell-effects"], parts: 2, title: "Spell effects" },
    { packs: ["feat-effects"], parts: 4, title: "Feat effects" },
    { packs: ["equipment-effects"], parts: 3, title: "Equipment effects" },
    { packs: ["bestiary-effects"], parts: 2, title: "Creature effects" },
];

export const EFFECT_PACKS = PARTS.flatMap((group) => group.packs);

/**
 * Number each item's part: `items` are `{ key, name, pack }`, already in pack order and by name within it.
 * A group cut into n parts is cut into n runs of as-equal-as-possible length.
 */
export function assignParts(items) {
    let part = 0;
    const out = [];
    for (const group of PARTS) {
        const members = items.filter((i) => group.packs.includes(i.pack));
        const size = Math.ceil(members.length / group.parts);
        members.forEach((item, n) => out.push({ ...item, part: part + 1 + Math.floor(n / size) }));
        part += group.parts;
    }
    return out;
}

/** The title of a part, by number. */
export function partTitle(part) {
    let first = 1;
    for (const group of PARTS) {
        if (part < first + group.parts) return group.parts === 1 ? group.title : `${group.title}, ${part - first + 1} of ${group.parts}`;
        first += group.parts;
    }
    return null;
}

/** The items an effect tracker lists, from its item table: `| CND-01 | \`conditionitems/frightened\` | …`. */
export function trackedEffects(markdown) {
    return [...String(markdown).matchAll(/^\| [A-Z]{2,4}-\d+ \| `([a-z0-9-]+\/[A-Za-z0-9-]+)` \|/gm)].map((m) => m[1]);
}

/** `Docs/pf2e-effects.md`: the inventory, part by part. */
export function inventoryDoc(inventory) {
    const parts = [...new Set(inventory.items.map((i) => i.part))].sort((a, b) => a - b);
    const lines = [
        "# pf2e's conditions and effects",
        "",
        `Generated by \`npm run index:pf2e\` from pf2e ${inventory.pf2e} — do not edit by hand. Every condition and effect`,
        `the system ships: **${inventory.items.length}** items, cut into ${parts.length} parts, each with its own issue and clause tracker in`,
        "`Docs/clauses/pf2e-effects/`.",
        "",
        "| Part | What | Items |",
        "| :-- | :-- | --: |",
        ...parts.map((p) => `| ${p} | ${partTitle(p)} | ${inventory.items.filter((i) => i.part === p).length} |`),
        "",
    ];
    for (const p of parts) {
        lines.push(`## Part ${p} — ${partTitle(p)}`, "", "| Item | Key | Level | Rule elements |", "| :-- | :-- | :-- | :-- |");
        for (const i of inventory.items.filter((x) => x.part === p)) {
            lines.push(`| ${i.name.replace(/\|/g, "\\|")} | \`${i.key}\` | ${i.level ?? ""} | ${i.rules.join(", ")} |`);
        }
        lines.push("");
    }
    return `${lines.join("\n").trimEnd()}\n`;
}
